import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import { rateLimit } from 'express-rate-limit';
import { env } from './config/env.js';
import { requestContext } from './middleware/request-context.js';
import { authRouter } from './modules/auth/auth.routes.js';
import { usersRouter } from './modules/users/users.routes.js';
import { dashboardRouter } from './modules/dashboard/dashboard.routes.js';
import { rolesRouter } from './modules/users/roles.routes.js';
import { auditRouter } from './modules/audit/audit.routes.js';
import { accountsRouter } from './modules/accounts/accounts.routes.js';
import { oauthRouter } from './modules/accounts/oauth.routes.js';
import { contentRouter } from './modules/content/content.routes.js';
import { mediaRouter } from './modules/content/media.routes.js';

export const app = express();
app.disable('x-powered-by');
app.set('trust proxy', 1);
// Cast: Vercel Node TS can type helmet's dual-package default export as a non-callable namespace.
app.use((helmet as unknown as () => express.RequestHandler)());
app.use(cors({ origin: env.WEB_ORIGIN, credentials: true, methods: ['GET', 'POST', 'PATCH', 'DELETE', 'OPTIONS'], allowedHeaders: ['Content-Type', 'X-Request-Id'] }));
app.use(express.json({ limit: '1mb' }));
app.use(cookieParser());
app.use(requestContext);
app.get('/health', (_req, res) => res.json({ status: 'ok', service: 'gpa-social-ai-api' }));
app.use('/api/v1/auth', rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, standardHeaders: 'draft-8', legacyHeaders: false }), authRouter);
app.use('/api/v1/users', usersRouter);
app.use('/api/v1/roles', rolesRouter);
app.use('/api/v1/audit', auditRouter);
app.use('/api/v1/dashboard', dashboardRouter);
app.use('/api/v1/accounts/oauth', rateLimit({ windowMs: 15 * 60 * 1000, limit: 60, standardHeaders: 'draft-8', legacyHeaders: false }), oauthRouter);
app.use('/api/v1/accounts', accountsRouter);
app.use('/api/v1/content', contentRouter);
app.use('/api/v1/media', mediaRouter);
app.use((_req, res) => res.status(404).json({ success: false, error: { code: 'NOT_FOUND', message: 'Endpoint not found.' }, meta: { requestId: res.locals.requestId } }));
app.use((err: any, _req: express.Request, res: express.Response, _next: express.NextFunction) => {
  console.error(JSON.stringify({ level: 'error', requestId: res.locals.requestId, message: err?.message ?? 'Unknown error' }));
  if (res.headersSent) return;
  res.status(500).json({ success: false, error: { code: 'INTERNAL_ERROR', message: 'An unexpected error occurred.' }, meta: { requestId: res.locals.requestId } });
});
